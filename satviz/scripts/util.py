# Contains few utility functions

import os
import ephem


def read_city_details(city_details_list, city_detail_file):
    """
    Reads city-wise details
    :param city_details_list: List to be populated
    :param city_detail_file: Input file
    :return: city_details_list
    """
    lines = [line.rstrip('\n') for line in open(city_detail_file)]
    for i in range(len(lines)):
        val = lines[i].split(",")
        city_details_list[int(val[0])] = {
            "name": val[1],
            "lat_deg": val[2],
            "long_deg": val[3],
            "alt_km": 0
        }
    return city_details_list


def generate_sat_obj_list(
        num_orbit,
        num_sats_per_orbit,
        epoch,
        phase_diff,
        inclination,
        eccentricity,
        arg_perigee,
        mean_motion,
        altitude
):
    """
    Generates list of satellite objects based on orbital elements
    :param num_orbit: Number of orbits
    :param num_sats_per_orbit: Number of satellites per orbit
    :param epoch: Epoch (start time)
    :param phase_diff: Phase difference between adjacent orbits
    :param inclination: Angle of inclination
    :param eccentricity: Eccentricity of orbits
    :param arg_perigee: Argument of perigee of orbits
    :param mean_motion: Mean motion in revolutions per day
    :param altitude: Altitude in metres
    :return: List of satellite objects
    """
    sat_objs = [None] * (num_orbit * num_sats_per_orbit)
    counter = 0
    for orb in range(0, num_orbit):
        raan = orb * 360 / num_orbit
        orbit_wise_shift = 0
        if orb % 2 == 1:
            if phase_diff:
                orbit_wise_shift = 360 / (num_sats_per_orbit * 2)

        for n_sat in range(0, num_sats_per_orbit):
            mean_anomaly = orbit_wise_shift + (n_sat * 360 / num_sats_per_orbit)

            sat = ephem.EarthSatellite()
            sat._epoch = epoch
            sat._inc = ephem.degrees(inclination)
            sat._e = eccentricity
            sat._raan = ephem.degrees(raan)
            sat._ap = arg_perigee
            sat._M = ephem.degrees(mean_anomaly)
            sat._n = mean_motion

            sat_objs[counter] = {
                "sat_obj": sat,
                "alt_km": altitude / 1000,
                "orb_id": orb,
                "orb_sat_id": n_sat

            }
            counter += 1
    return sat_objs


def read_constellation(gen_data_dir):
    """
    Reads a constellation generated by satgenpy (a directory in gen_data)
    :param gen_data_dir: Directory with tles.txt, isls.txt and ground_stations.txt
    :return: Dictionary: {
                "name":             Name of the generated constellation (directory name)
                "num_orbs":         Number of orbits
                "num_sats_per_orb": Number of satellites per orbit
                "epoch":            Epoch of the TLEs (start time)
                "sat_objs":         List of satellite objects
                "isls":             List of ISLs as (sat1, sat2); empty if there is no isls.txt
                "city_details":     Ground station details; empty if there is no ground_stations.txt
             }
    """
    if not os.path.isfile(os.path.join(gen_data_dir, "tles.txt")):
        raise ValueError("Not a generated constellation (tles.txt is missing): " + gen_data_dir)

    sat_objs = []
    with open(os.path.join(gen_data_dir, "tles.txt")) as f:
        num_orbit, num_sats_per_orbit = [int(n) for n in f.readline().split()]
        for tle_line_1 in f:
            sat = ephem.readtle(tle_line_1, f.readline(), f.readline())
            sat_objs.append({
                "sat_obj": sat,
                "alt_km": 0,
                "orb_id": len(sat_objs) // num_sats_per_orbit,
                "orb_sat_id": len(sat_objs) % num_sats_per_orbit
            })
    if len(sat_objs) == 0:
        raise ValueError("No satellites in " + os.path.join(gen_data_dir, "tles.txt"))
    epoch = sat_objs[0]["sat_obj"]._epoch.datetime().strftime("%Y-%m-%d %H:%M:%S")
    compute_sat_positions(sat_objs, epoch)

    isls = []
    isls_file = os.path.join(gen_data_dir, "isls.txt")
    if os.path.isfile(isls_file):
        with open(isls_file) as f:
            for line in f:
                val = line.split()
                if len(val) >= 2:
                    isls.append((int(val[0]), int(val[1])))

    city_details = {}
    city_detail_file = os.path.join(gen_data_dir, "ground_stations.txt")
    if os.path.isfile(city_detail_file):
        city_details = read_city_details(city_details, city_detail_file)

    return {
        "name": os.path.basename(os.path.normpath(gen_data_dir)),
        "num_orbs": num_orbit,
        "num_sats_per_orb": num_sats_per_orbit,
        "epoch": epoch,
        "sat_objs": sat_objs,
        "isls": isls,
        "city_details": city_details
    }


def compute_sat_positions(sat_objs, epoch):
    """
    Computes the position of all satellites at the given time
    :param sat_objs: List of satellite objects
    :param epoch: Time at which to compute the positions
    :return: None
    """
    for i in range(len(sat_objs)):
        sat_objs[i]["sat_obj"].compute(epoch)
        sat_objs[i]["alt_km"] = sat_objs[i]["sat_obj"].elevation / 1000


def get_neighbor_satellite(
        sat1_orb,
        sat1_rel_id,
        sat2_orb,
        sat2_rel_id,
        sat_positions,
        num_orbits,
        num_sats_per_orbit):
    """
    Get satellite id of neighboring satellite
    :param sat1_orb: Orbit id of satellite
    :param sat1_rel_id: Relative index of satellite within orbit
    :param sat2_orb: Relative orbit of neighbor
    :param sat2_rel_id: Relative index of neighbor
    :param sat_positions: List of satellite objects
    :param num_orbits: Number of orbits
    :param num_sats_per_orbit: Number of satellites per orbit
    :return: satellite id of neighboring satellite
    """
    neighbor_abs_orb = (sat1_orb + sat2_orb) % num_orbits
    neighbor_abs_pos = (sat1_rel_id + sat2_rel_id) % num_sats_per_orbit
    sel_sat_id = -1
    for i in range(0, len(sat_positions)):
        if sat_positions[i]["orb_id"] == neighbor_abs_orb and sat_positions[i]["orb_sat_id"] == neighbor_abs_pos:
            sel_sat_id = i
            break
    return sel_sat_id


def find_orbit_links(sat_positions, num_orbit, num_sats_per_orbit):
    """
    Orbit is visualized by connecting consecutive satellites within te orbit.
    This function returns such satellite-satellite connections
    :param sat_positions: List of satellite objects
    :param num_orbit: Number of orbits
    :param num_sats_per_orbit: Number of satellites per orbit
    :return: Components of orbit
    """
    orbit_links = {}
    cntr = 0
    for i in range(0, len(sat_positions)):
        sel_sat_id = get_neighbor_satellite(sat_positions[i]["orb_id"], sat_positions[i]["orb_sat_id"],
                                                 0, 1, sat_positions, num_orbit, num_sats_per_orbit)
        orbit_links[cntr] = {
            "sat1": i,
            "sat2": sel_sat_id,
            "dist": -1.0
        }
        cntr += 1
    return orbit_links


def find_grid_links(sat_positions, num_orbit, num_sats_per_orbit):
    """
    Generates +Grid connectivity between satellites
    :param sat_positions: List of satellite objects
    :param num_orbit: Number of orbits
    :param num_sats_per_orbit: Number of satellites per orbit
    :return: +Grid links
    """
    grid_links = {}
    cntr = 0
    for i in range(0, len(sat_positions)):
        sel_sat_id = get_neighbor_satellite(sat_positions[i]["orb_id"], sat_positions[i]["orb_sat_id"],
                                                 0, 1, sat_positions,
                                                 num_orbit, num_sats_per_orbit)
        grid_links[cntr] = {
            "sat1": i,
            "sat2": sel_sat_id,
            "dist": -1.0
        }
        cntr += 1
        sel_sat_id = get_neighbor_satellite(sat_positions[i]["orb_id"], sat_positions[i]["orb_sat_id"],
                                                 1, 0, sat_positions,
                                                 num_orbit, num_sats_per_orbit)
        grid_links[cntr] = {
            "sat1": i,
            "sat2": sel_sat_id,
            "dist": -1.0
        }
        cntr += 1
    #print("num links:", cntr)
    return grid_links


CESIUM_TOKEN_PLACEHOLDER = "<CESIUM_ACCESS_TOKEN>"
CESIUM_TOKEN_FILE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "cesium_token.txt")


def read_cesium_token():
    """
    Finds the Cesium access token: the CESIUM_ACCESS_TOKEN environment variable,
    or else the (untracked) file satviz/cesium_token.txt
    :return: Cesium access token
    """
    token = os.environ.get("CESIUM_ACCESS_TOKEN", "").strip()
    if not token and os.path.isfile(CESIUM_TOKEN_FILE):
        with open(CESIUM_TOKEN_FILE, 'r') as f:
            token = f.read().strip()
    if not token:
        raise ValueError("No Cesium access token: set the CESIUM_ACCESS_TOKEN environment variable "
                         "or put the token in satviz/cesium_token.txt")
    return token


def write_viz_files(viz_string, top_file, bottom_file, out_file):
    """
    Generates HTML visualization file
    :param viz_string: HTML formatted string
    :param top_file: top part of the HTML file
    :param bottom_file: bottom part of the HTML file
    :param out_file: output HTML file
    :return: None
    """
    with open(top_file, 'r') as fi:
        top = fi.read()
    if CESIUM_TOKEN_PLACEHOLDER in top:
        top = top.replace(CESIUM_TOKEN_PLACEHOLDER, read_cesium_token())
    writer_html = open(out_file, 'w')
    writer_html.write(top)
    writer_html.write(viz_string)
    with open(bottom_file, 'r') as fb:
        writer_html.write(fb.read())
    writer_html.close()

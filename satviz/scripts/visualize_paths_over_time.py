constellation = util.read_constellation(args.gen_data_dir)
NAME = constellation["name"]
sat_objs = constellation["sat_objs"]
city_details = constellation["city_details"]


def read_path_file(path_file):
    """
    Reads the changes of a path over time
    :param path_file: Path file (lines of <time in ns>,<node>-<node>-...; or Unreachable instead of the nodes)
    :return: List of [time in s, list of node ids]; the list of node ids is empty while there is no path
    """
    changes = []
    with open(path_file) as f:
        for line in f:
            val = line.strip().split(",")
            if len(val) < 2:
                continue
            nodes = (
                [int(n) for n in val[1].split("-")] if val[1] != "Unreachable" else []
            )
            for n in nodes:
                if n >= len(sat_objs) and (n - len(sat_objs)) not in city_details:
                    raise ValueError(
                        "Node %d of %s is not in the constellation %s"
                        % (n, path_file, NAME)
                    )
            changes.append([int(val[0]) / 1e9, nodes])
    if len(changes) == 0:
        raise ValueError("No paths in " + path_file)
    return changes


def find_duration_s(path_files, paths):
    """
    Finds the duration of the scene from the path files
    :param path_files: Path files
    :param paths: Changes over time of each path
    :return: Duration in s
    """
    duration_s = 0
    for path_file in path_files:
        match = re.search(r"\d+ms_for_(\d+)s", os.path.abspath(path_file))
        if match:
            duration_s = max(duration_s, int(match.group(1)))
    if duration_s == 0:
        duration_s = max(changes[-1][0] for changes in paths) + DURATION_MARGIN_S
    return duration_s


def generate_sat_positions_over_time(sample_times_s):
    """
    Computes the positions of all satellites at the given times
    :param sample_times_s: Times in s since the epoch
    :return: For each satellite a flat list of longitude (deg), latitude (deg), altitude (m) for each time
    """
    epoch = ephem.Date(sat_objs[0]["sat_obj"]._epoch)
    positions = [[] for _ in sat_objs]
    for t in sample_times_s:
        now = ephem.Date(epoch + t * ephem.second)
        for i in range(len(sat_objs)):
            sat = sat_objs[i]["sat_obj"]
            sat.compute(now)
            positions[i] += [
                round(math.degrees(sat.sublong), 4),
                round(math.degrees(sat.sublat), 4),
                round(sat.elevation),
            ]
    return positions


def endpoint_name(node):
    """
    :param node: Node id
    :return: Name of the ground station (or else the satellite id)
    """
    if node >= len(sat_objs):
        return city_details[node - len(sat_objs)]["name"]
    return "Satellite " + str(node)


def generate_paths_over_time():
    """
    Generates the satellites and the end-to-end paths over time
    :return: HTML formatted string for visualization, and the output HTML file
    """
    paths = [read_path_file(path_file) for path_file in args.path_files]
    duration_s = (
        args.duration_s
        if args.duration_s is not None
        else find_duration_s(args.path_files, paths)
    )
    if duration_s <= 0 or args.step_s <= 0:
        raise ValueError("The duration and the step must be positive")

    # One sample past the end, such that the whole duration can be interpolated
    num_samples = int(math.ceil(duration_s / args.step_s)) + 1
    sample_times_s = [i * args.step_s for i in range(num_samples)]
    print(
        "Computing",
        num_samples,
        "positions of",
        len(sat_objs),
        "satellites for",
        duration_s,
        "s",
    )
    sat_positions = generate_sat_positions_over_time(sample_times_s)

    routes = []
    ground_stations = {}
    out_html_file = OUT_DIR + NAME + "_paths_over_time"
    for i in range(len(paths)):
        # The endpoints are those of the first moment at which there is a path
        nodes = next((nodes for (_, nodes) in paths[i] if len(nodes) > 0), [])
        name = os.path.basename(args.path_files[i])
        if len(nodes) > 0:
            name = endpoint_name(nodes[0]) + " to " + endpoint_name(nodes[-1])
            if len(paths) <= 2:
                out_html_file += (
                    "_"
                    + endpoint_name(nodes[0]).replace(" ", "_")
                    + "_"
                    + str(nodes[0])
                    + "_"
                    + endpoint_name(nodes[-1]).replace(" ", "_")
                    + "_"
                    + str(nodes[-1])
                )
        print(name + ":", len(paths[i]), "path changes")
        routes.append(
            {
                "name": name,
                "color": PATH_COLORS[i % len(PATH_COLORS)],
                "changes": paths[i],
            }
        )
        for _, nodes in paths[i]:
            for n in nodes:
                if n >= len(sat_objs):
                    gs = city_details[n - len(sat_objs)]
                    ground_stations[n] = {
                        "name": gs["name"],
                        "pos": [
                            float(gs["long_deg"]),
                            float(gs["lat_deg"]),
                            gs["alt_km"] * 1000,
                        ],
                        "endpoint": n in (nodes[0], nodes[-1])
                        or ground_stations.get(n, {}).get("endpoint", False),
                    }
    if len(paths) > 2:
        out_html_file += "_" + str(len(paths)) + "_paths"
    out_html_file += ".html"

    data = {
        "epoch": constellation["epoch"].replace(" ", "T") + "Z",
        "duration_s": duration_s,
        "step_s": args.step_s,
        "speed": args.speed,
        "sat_positions": sat_positions,
        "ground_stations": ground_stations,
        "routes": routes,
        "isls": constellation["isls"] if args.isls else [],
    }
    viz_string = (
        "var data = " + json.dumps(data, separators=(",", ":")) + ";\n" + VIZ_JS
    )
    return viz_string, out_html_file


